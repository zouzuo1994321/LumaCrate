def _build_char_map(raw: str) -> dict:
    if len(raw) % 2:
        raise ValueError(f"字形对照表长度必须是偶数，实际 {len(raw)}")
    out = {}
    for i in range(0, len(raw), 2):
        a, b = raw[i], raw[i + 1]
        if a != b:          # 同形的不必进表（写了也白写，直接丢）
            out[a] = b
    return out


CHAR_MAP = _build_char_map(_CHAR_PAIRS_RAW)

# 一次最多给几个候选串。调用方会把每个候选都跑一遍模糊匹配，
# 候选太多 = 引导芯片爆炸 + 打分变慢，卡在 6 个足够覆盖「一个词 + 一两个修饰」。
MAX_VARIANTS = 6

_WS = re.compile(r"[\s　]+")


def _clean(s) -> str:
    return _WS.sub("", str(s or "")).strip()


def convert_chars(text: str) -> str:
    """逐字把简体字换成日本新字体（未收录的字原样保留）。"""
    return "".join(CHAR_MAP.get(ch, ch) for ch in text)


def _replace_terms(src: str, max_hits: int = 4) -> str:
    """把输入里出现的术语换成日文（长词优先，最多替换 ``max_hits`` 处）。"""
    out = src
    hits = 0
    for k in _KEYS_BY_LEN:
        if hits >= max_hits:
            break
        if len(k) >= 2 and k in out:
            out = out.replace(k, LEXICON[k][0])
            hits += 1
    return out


def _term_candidates(src: str, max_terms: int = 3):
    """输入里出现的术语各自的日文候选（长词优先，最多 ``max_terms`` 个词）。

    为什么需要这一层：整串译文往往**一条都命中不了** —— 输入「孕妇教师」，
    整串换成「妊婦教師」后，库里没有任何标签含这四个字。真正有用的是把它
    **拆成「妊婦」「教師」两条**分别去模糊匹配。少这一层，多词输入会显得「没生效」。
    """
    out = []
    for k in _KEYS_BY_LEN:
        if len(out) >= max_terms:
            break
        if len(k) >= 2 and k in src:
            out.append(k)
    for k in out:
        for cand in LEXICON[k]:
            yield cand


def translate_zh_to_ja(text, limit: int = MAX_VARIANTS) -> list:
    """把中文引导词翻成**日文候选串**。

    返回 ``list[str]``：已去重、已剔除与原串相同的项、按可信度从高到低，
    最多 ``limit`` 条。原串本身不是中文、或本来就是日文写法时返回 ``[]``
    （调用方据此可以完全跳过这一步，零开销）。

    >>> translate_zh_to_ja("轮奸")
    ['輪姦', '輪姦し']
    >>> translate_zh_to_ja("三上悠亚")
    ['三上悠亜']
    >>> translate_zh_to_ja("孕妇教师")
    ['妊婦教師', '妊婦', '教師']
    """
    src = _clean(text)
    if len(src) < 2:            # 模糊匹配本身也要求 ≥2 字，单字没有意义
        return []
    try:
        limit = max(1, min(24, int(limit)))
    except (TypeError, ValueError):
        limit = MAX_VARIANTS

    out, seen = [], set()

    def add(s):
        s = _clean(s)
        if len(s) < 2 or s == src or s in seen or len(out) >= limit:
            return
        seen.add(s)
        out.append(s)

    # ① 整词命中词典 —— 最可信，排最前
    for cand in LEXICON.get(src, ()):
        add(cand)

    # ② 子串替换：把输入里出现的术语换成日文（「孕妇教师」→「妊婦教師」）
    replaced = _replace_terms(src)
    if replaced != src:
        add(replaced)
        for cand in LEXICON.get(replaced, ()):
            add(cand)

    # ③ 逐词译文：把输入拆成各术语、各自给日文候选（多词输入真正命中的是这一层）
    for cand in _term_candidates(src):
        add(cand)

    # ④ 字形转换兜底：覆盖词典没收的写法，也顺手解决艺人名（三上悠亚 → 三上悠亜）
    add(convert_chars(src))
    if replaced != src:
        add(convert_chars(replaced))

    return out
